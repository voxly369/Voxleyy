-- ---------------------------------------------------------------------------
-- Invite check (anon-safe, no enumeration)
-- ---------------------------------------------------------------------------

create or replace function public.check_invite_code(p_code text) returns boolean
language plpgsql security definer set search_path = public as $$
declare
  normalized text := upper(btrim(coalesce(p_code, '')));
  row public.invite_codes%rowtype;
  sk text := coalesce(auth.uid()::text, 'anon:' || coalesce(current_setting('request.jwt.claim.sub', true), 'anon'));
begin
  perform public.record_invite_attempt(sk);
  if normalized !~ '^[A-HJ-NP-Z2-9]{10}$' then return false; end if;
  select * into row from public.invite_codes where code = normalized;
  if not found then return false; end if;
  if row.revoked or (row.expires_at is not null and row.expires_at <= now()) or row.uses >= row.max_uses then
    return false;
  end if;
  return true;
end;
$$;

revoke all on function public.check_invite_code(text) from public;
grant execute on function public.check_invite_code(text) to anon, authenticated;

create or replace function public.consume_invite_code_for_signup(p_code text) returns void
language plpgsql security definer set search_path = public as $$
declare
  normalized text := upper(btrim(coalesce(p_code, '')));
  row public.invite_codes%rowtype;
begin
  if normalized !~ '^[A-HJ-NP-Z2-9]{10}$' then
    raise exception 'That invite code isn''t valid.';
  end if;
  select * into row from public.invite_codes where code = normalized for update;
  if not found or row.revoked or (row.expires_at is not null and row.expires_at <= now())
     or row.uses >= row.max_uses then
    raise exception 'That invite code isn''t valid.';
  end if;
  update public.invite_codes set uses = uses + 1 where code = normalized;
end;
$$;

revoke all on function public.consume_invite_code_for_signup(text) from public, anon, authenticated;


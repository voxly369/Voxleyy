import { writeFileSync } from 'node:fs'

const groups = ['Nature', 'Writing', 'Symbols', 'Shapes', 'Decor']
const stickers = []
for (let i = 1; i <= 60; i += 1) {
  const group = groups[i % groups.length]
  const name = `${group} mark ${i}`
  const hue = (i * 47) % 360
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="${name}"><circle cx="32" cy="32" r="28" fill="hsl(${hue} 45% 45%)" opacity="0.9"/><path d="M20 32h24M32 20v24" stroke="#fff" stroke-width="4" stroke-linecap="round"/></svg>`
  stickers.push({ id: `sticker-${i}`, name, group, svg })
}

const categories = [
  'Poetry',
  'Fantasy',
  'Romance',
  'Faith',
  'Memoir',
  'Minimal',
  'Typographic',
  'Dark',
  'Light',
]
const templates = []
let t = 0
for (const category of categories) {
  for (let v = 0; v < 4; v += 1) {
    t += 1
    const bg =
      category === 'Dark'
        ? '#1a100a'
        : category === 'Light' || category === 'Minimal'
          ? '#f5f0eb'
          : category === 'Romance'
            ? '#4a2038'
            : category === 'Fantasy'
              ? '#1e2a44'
              : category === 'Faith'
                ? '#2c2416'
                : '#3d2c24'
    const text = category === 'Light' || category === 'Minimal' ? '#1a100a' : '#ffffff'
    templates.push({
      id: `tpl-${category.toLowerCase()}-${v + 1}`,
      category,
      name: `${category} ${v + 1}`,
      design: {
        version: 1,
        width: 1600,
        height: 2400,
        background: { type: 'solid', color: bg },
        layers: [
          {
            id: 'title',
            type: 'text',
            x: 800,
            y: 1100,
            width: 1200,
            height: 200,
            rotation: 0,
            opacity: 1,
            locked: false,
            hidden: false,
            text: 'Title',
            fontFamily: 'Fraunces',
            fontSize: 96,
            fontWeight: 600,
            fontStyle: 'normal',
            color: text,
            align: 'center',
            lineHeight: 1.1,
            letterSpacing: 0,
            uppercase: false,
            shadow: null,
            outline: null,
            highlight: null,
          },
          {
            id: 'author',
            type: 'text',
            x: 800,
            y: 1900,
            width: 900,
            height: 80,
            rotation: 0,
            opacity: 1,
            locked: false,
            hidden: false,
            text: 'Author',
            fontFamily: 'Lora',
            fontSize: 48,
            fontWeight: 500,
            fontStyle: 'normal',
            color: text,
            align: 'center',
            lineHeight: 1.2,
            letterSpacing: 0,
            uppercase: false,
            shadow: null,
            outline: null,
            highlight: null,
          },
        ],
      },
    })
  }
}

writeFileSync(
  new URL('../src/lib/coverStudio/stickers.generated.ts', import.meta.url),
  `/** Generated by scripts/generate-cover-studio-assets.mjs — do not edit by hand. */\nexport type CoverSticker = { id: string; name: string; group: string; svg: string }\nexport const COVER_STICKERS: CoverSticker[] = ${JSON.stringify(stickers, null, 2)}\n`,
)
writeFileSync(
  new URL('../src/lib/coverStudio/templates.generated.ts', import.meta.url),
  `/** Generated by scripts/generate-cover-studio-assets.mjs */\nimport type { CoverDesignDocument } from './designSchema.ts'\nexport type CoverTemplate = { id: string; category: string; name: string; design: CoverDesignDocument }\nexport const COVER_TEMPLATES: CoverTemplate[] = ${JSON.stringify(templates, null, 2)}\n`,
)

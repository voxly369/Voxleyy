#!/usr/bin/env node
/**
 * Generates supabase/seeds/languages.generated.sql and
 * src/lib/languages/languagesList.generated.ts from Intl.DisplayNames.
 * Run: node scripts/generate-languages.mjs
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const sqlPath = join(__dirname, '../supabase/seeds/languages.generated.sql')
const tsPath = join(__dirname, '../src/lib/languages/languagesList.generated.ts')

const displayNamesEn = new Intl.DisplayNames(['en'], { type: 'language' })

/** ISO 639-1 two-letter codes that resolve to a distinct English display name. */
function collectLanguageCodes() {
  const rows = []
  for (let i = 0; i < 26; i += 1) {
    for (let j = 0; j < 26; j += 1) {
      const code = String.fromCharCode(97 + i) + String.fromCharCode(97 + j)
      let nameEn
      try {
        nameEn = displayNamesEn.of(code)
      } catch {
        continue
      }
      if (!nameEn || nameEn === code || nameEn.length < 2) continue
      let nameNative = nameEn
      try {
        nameNative = new Intl.DisplayNames([code], { type: 'language' }).of(code) ?? nameEn
      } catch {
        nameNative = nameEn
      }
      rows.push({ code, nameEn, nameNative })
    }
  }
  rows.sort((a, b) => a.nameEn.localeCompare(b.nameEn))
  return rows
}

function sqlEscape(value) {
  return value.replace(/'/g, "''")
}

const rows = collectLanguageCodes()

const sqlLines = [
  '-- Generated by scripts/generate-languages.mjs — do not edit by hand.',
  'insert into public.languages (code, name_en, name_native)',
  'values',
  ...rows.map((row, index) => {
    const comma = index < rows.length - 1 ? ',' : ''
    return `  ('${row.code}', '${sqlEscape(row.nameEn)}', '${sqlEscape(row.nameNative)}')${comma}`
  }),
  'on conflict (code) do update set',
  '  name_en = excluded.name_en,',
  '  name_native = excluded.name_native;',
  '',
]

writeFileSync(sqlPath, sqlLines.join('\n'), 'utf8')
console.error(`Wrote ${rows.length} languages to ${sqlPath}`)

const tsLines = [
  '// Generated by scripts/generate-languages.mjs — do not edit by hand.',
  'export type LanguageListEntry = { code: string; nameEn: string; nameNative: string }',
  'export const LANGUAGES_LIST: readonly LanguageListEntry[] = [',
  ...rows.map(
    (row) =>
      `  { code: '${row.code}', nameEn: '${row.nameEn.replace(/'/g, "\\'")}', nameNative: '${row.nameNative.replace(/'/g, "\\'")}' },`,
  ),
  '] as const',
  'export const KNOWN_LANGUAGE_CODES: ReadonlySet<string> = new Set(LANGUAGES_LIST.map((l) => l.code))',
  '',
]

writeFileSync(tsPath, tsLines.join('\n'), 'utf8')
console.error(`Wrote ${rows.length} languages to ${tsPath}`)

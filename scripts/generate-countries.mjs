function sqlEscape(value) {
  return value.replace(/'/g, "''")
}

/** Primary language for a region via Intl.Locale maximize (ICU default). */
function inferMainLanguages(countryCode) {
  try {
    const lang = new Intl.Locale('und', { region: countryCode }).maximize().language
    if (!lang || !/^[a-z]{2}$/.test(lang)) return null
    return [lang]
  } catch {
    return null
  }
}

function sqlTextArray(codes) {
  if (!codes?.length) return 'null'
  return `ARRAY[${codes.map((c) => `'${c}'`).join(', ')}]::text[]`
}

const codes = []
for (let i = 65; i <= 90; i++) {
  for (let j = 65; j <= 90; j++) {
    codes.push(String.fromCharCode(i) + String.fromCharCode(j))
  }
}

const rows = []
for (const code of codes) {
  const name = regionNames.of(code)
  if (!name || name === code) continue
  const tz = SINGLE_ZONE[code] ?? null
  const mainLanguages = inferMainLanguages(code)
  rows.push({ code, name, tz, mainLanguages })
}

rows.sort((a, b) => a.name.localeCompare(b.name))

const lines = [
  '-- Generated by scripts/generate-countries.mjs — do not edit by hand.',
  'insert into public.countries (code, name, primary_timezone, main_languages)',
  'values',
]

const valueLines = rows.map((row, index) => {
  const tz = row.tz ? `'${sqlEscape(row.tz)}'` : 'null'
  const langs = sqlTextArray(row.mainLanguages)
  const comma = index < rows.length - 1 ? ',' : ''
  return `  ('${row.code}', '${sqlEscape(row.name)}', ${tz}, ${langs})${comma}`
})

lines.push(...valueLines)
lines.push('on conflict (code) do update set')
lines.push('  name = excluded.name,')
lines.push('  primary_timezone = coalesce(excluded.primary_timezone, countries.primary_timezone),')
lines.push('  main_languages = coalesce(excluded.main_languages, countries.main_languages);')
lines.push('')

const mainLangPath = join(__dirname, '../supabase/seeds/countries_main_languages.generated.sql')
const updateLines = [
  '-- Generated by scripts/generate-countries.mjs — do not edit by hand.',
  ...rows
    .filter((row) => row.mainLanguages?.length)
    .map(
      (row) =>
        `update public.countries set main_languages = ${sqlTextArray(row.mainLanguages)} where code = '${row.code}';`,
    ),
  '',
]
writeFileSync(mainLangPath, updateLines.join('\n'), 'utf8')
const emptyMain = rows.filter((row) => !row.mainLanguages?.length)
console.error(`Countries without inferred main languages: ${emptyMain.length}`)
console.error(emptyMain.map((r) => r.code).join(', '))

writeFileSync(outPath, lines.join('\n'), 'utf8')
console.error(`Wrote ${rows.length} countries to ${outPath}`)

const tsPath = join(__dirname, '../src/lib/signup/countriesList.generated.ts')
